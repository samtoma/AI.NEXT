export const meta = {
  name: 'refutation',
  description: 'Authors the explanation / refutation library for the maths LOs (ADR-0007, Phase 6)',
  phases: [
    { title: 'Misconceptions', detail: 'enumerate the wrong turns each LO actually invites (Sonnet)' },
    { title: 'Author', detail: 'worked example / faded / contrasting case / refutation per LO (Sonnet)' },
    { title: 'Verify', detail: 'independent check against the canonical solution — author ≠ grader (Sonnet)' },
  ],
}

/*
 * WHY THIS EXISTS
 *
 * The PRD's central teaching bet is that a student who gets something wrong
 * should meet content authored for THAT specific wrong turn, not a re-derived
 * explanation. This workflow produces that content for the 90 maths learning
 * objectives already in the spine.
 *
 * ⚠️  THE HUMAN REVIEW GATE IS SUSPENDED FOR THIS OUTPUT.
 * Constitution v2.0.0 Principle III, suspended by ADR-0007 (decisions.md Q8):
 * no reviewer exists at this stage, so these rows ship unreviewed to real pilot
 * students behind Cloudflare Access.
 *
 * That makes the Verify phase below the ONLY quality gate between this content
 * and a child. It is therefore written to be adversarial and to FAIL CLOSED:
 * an entry that the verifier cannot confirm against the canonical solution is
 * dropped from the output, not shipped with a warning. A missing refutation is
 * a handled state at runtime (FR-305: fall back to the canonical solution and
 * raise an authoring-gap flag). A WRONG refutation is not — it teaches the
 * misconception it was supposed to correct, inside the very metric the
 * comparison measures.
 *
 * Input: the maths seed bundles (already validated, already loaded).
 * Output: { records: [...] } → assemble_refutations.py → seed/refutations-math.json
 */

// ---- source data -----------------------------------------------------------
// Stage-0 manifest, generated by build_lo_manifest.py from the SHIPPED seed
// bundles — not re-read from the PDF. That matters: the library must be anchored
// to the same 90 objectives and 450 canonical solutions both environments
// actually serve, so a refutation can never argue against a solution the student
// is not graded on.
//
//   uv run build_lo_manifest.py            # writes manifest/math-los.json
//
// The manifest is injected as MANIFEST (same convention as LO_FILTER below).
// It is 90 objectives deep, so unlike the smaller extraction workflows it is
// not inlined here.
if (typeof MANIFEST === 'undefined' || !MANIFEST || !MANIFEST.learning_objectives) {
  throw new Error(
    'MANIFEST not provided. Run `uv run build_lo_manifest.py` and inject ' +
    'manifest/math-los.json as MANIFEST before running this workflow.'
  )
}

// Optional: restrict to a subset while iterating, e.g. ['lo:u1-1-1'].
const ONLY = (typeof LO_FILTER !== 'undefined' && LO_FILTER) || null

const STEP = {
  type: 'object', required: ['step', 'text_md'],
  properties: { step: { type: 'integer' }, text_md: { type: 'string' } },
}

const MISC_SCHEMA = {
  type: 'object', required: ['lo', 'misconceptions'],
  properties: {
    lo: { type: 'string' },
    misconceptions: {
      type: 'array',
      items: {
        type: 'object', required: ['label', 'description'],
        properties: {
          label: { type: 'string' },
          description: { type: 'string' },
          // Optional on purpose: a GUESSED signal drives a wrong diagnosis,
          // which is worse than no diagnosis. Omit rather than invent.
          signal: { type: 'string' },
        },
      },
    },
  },
}

const ENTRIES_SCHEMA = {
  type: 'object', required: ['lo', 'entries'],
  properties: {
    lo: { type: 'string' },
    entries: {
      type: 'array',
      items: {
        type: 'object', required: ['entry_type', 'content'],
        properties: {
          entry_type: { type: 'string', enum: ['worked_example', 'faded', 'contrasting_case', 'refutation'] },
          misconception_label: { type: 'string' },
          title: { type: 'string' },
          source_page: { type: 'integer' },
          content: { type: 'array', items: STEP },
        },
      },
    },
  },
}

const VERIFY_SCHEMA = {
  type: 'object', required: ['lo', 'verdicts'],
  properties: {
    lo: { type: 'string' },
    verdicts: {
      type: 'array',
      items: {
        type: 'object', required: ['index', 'verdict', 'reason'],
        properties: {
          index: { type: 'integer' },
          verdict: { type: 'string', enum: ['CONFIRMED', 'CONTRADICTS_CANONICAL', 'UNSUPPORTED', 'UNCLEAR'] },
          reason: { type: 'string' },
        },
      },
    },
  },
}

const RULES = `RULES (non-negotiable — this content reaches students UNREVIEWED):
- The canonical solution is the authority. Never contradict its method or its final answer.
- Teach only mathematics that the given LO and its questions actually cover. No outside technique.
- Cite the book page when the LO carries one; omit the field rather than guess a page.
- Write in ENGLISH — this is the English-medium maths book.
- Plain, warm, concrete. A step is one idea. No preamble, no encouragement filler.
- If you cannot author something honestly for this LO, return fewer entries. Fewer is correct; padding is not.`

// ---- prompts ---------------------------------------------------------------
const miscPrompt = (lo) => `You are a mathematics teacher who has marked thousands of these papers.

LEARNING OBJECTIVE ${lo.id}: "${lo.label}"
${lo.description ? `Description: ${lo.description}` : ''}
${lo.page ? `Book page: ${lo.page}` : ''}

QUESTIONS students answer on this objective, with the canonical solutions:
${JSON.stringify(lo.questions, null, 1).slice(0, 9000)}

${RULES}

Enumerate the WRONG TURNS this objective actually invites — the specific errors a
real student makes here, not generic ones ("careless mistake", "didn't study" are
useless). Each must be a distinct, diagnosable procedure that produces a
predictable wrong answer.

For each: a short label, a description of what the student is doing, and — ONLY
when it is genuinely recognisable from a final answer — a signal describing how
it shows up. Omit signal when the error is only visible in working.

Return at most 4. Return fewer, or none, if this objective does not invite
distinct misconceptions. Output MISC_SCHEMA with lo="${lo.id}".`

const authorPrompt = (lo, misc) => `You are authoring the teaching library for one objective.

LEARNING OBJECTIVE ${lo.id}: "${lo.label}"
${lo.page ? `Book page: ${lo.page}` : ''}

CANONICAL SOLUTIONS (the authority — never contradict these):
${JSON.stringify(lo.questions, null, 1).slice(0, 9000)}

MISCONCEPTIONS identified for this objective:
${(misc.misconceptions || []).map((m, i) => `${i + 1}. ${m.label} — ${m.description}`).join('\n') || '(none)'}

${RULES}

Author entries:
- one "worked_example": the canonical method done cleanly, step by step;
- optionally one "faded": the same method with the later steps left to the student;
- for EACH misconception, one "refutation": address that specific wrong turn —
  show the student where their reasoning diverges and why it fails, using the
  canonical method. Set misconception_label to the EXACT label above.
- optionally one "contrasting_case": two nearly-identical problems where the
  misconception changes the answer.

A refutation must argue against the specific error, not restate the correct
method. If the only honest thing you can write is a restatement, omit it —
runtime falls back to the canonical solution, which is a good outcome.

Output ENTRIES_SCHEMA with lo="${lo.id}".`

const verifyPrompt = (lo, entries) => `You are a DIFFERENT teacher checking a colleague's work. You did not write this.

LEARNING OBJECTIVE ${lo.id}: "${lo.label}"

CANONICAL SOLUTIONS (the authority):
${JSON.stringify(lo.questions, null, 1).slice(0, 9000)}

ENTRIES TO CHECK (index is 0-based):
${JSON.stringify(entries.entries || [], null, 1).slice(0, 12000)}

This content will reach real students WITHOUT human review. You are the only
check. Be adversarial: work each entry through yourself before judging it.

For each entry return a verdict:
- CONFIRMED               — mathematically correct AND consistent with the canonical method and answer.
- CONTRADICTS_CANONICAL   — uses a different method, or reaches a different answer.
- UNSUPPORTED             — introduces material this objective does not cover.
- UNCLEAR                 — you cannot confirm it is correct.

Only CONFIRMED entries are kept. When in doubt, do NOT return CONFIRMED: a
dropped entry costs a fallback to the canonical solution, while a wrong one
teaches a child the error it was meant to fix.

Output VERIFY_SCHEMA with lo="${lo.id}".`

// ---- run -------------------------------------------------------------------
const los = MANIFEST.learning_objectives.filter((lo) => !ONLY || ONLY.includes(lo.id))
if (los.length === 0) throw new Error('no learning objectives selected — check LO_FILTER')
log(`authoring library for ${los.length} learning objectives`)

const records = await parallel(los.map((lo) => async () => {
  const misc = await agent(miscPrompt(lo), {
    label: `misc:${lo.id}`, phase: 'Misconceptions', model: 'sonnet', schema: MISC_SCHEMA,
  })
  const entries = await agent(authorPrompt(lo, misc), {
    label: `author:${lo.id}`, phase: 'Author', model: 'sonnet', schema: ENTRIES_SCHEMA,
  })
  const verdicts = await agent(verifyPrompt(lo, entries), {
    label: `verify:${lo.id}`, phase: 'Verify', model: 'sonnet', schema: VERIFY_SCHEMA,
  })

  // FAIL CLOSED. Anything not explicitly CONFIRMED is dropped, including
  // entries the verifier simply did not mention — silence is not approval.
  const ok = new Map((verdicts.verdicts || []).map((v) => [v.index, v]))
  const kept = []
  const dropped = []
  ;(entries.entries || []).forEach((e, i) => {
    const v = ok.get(i)
    if (v && v.verdict === 'CONFIRMED') kept.push(e)
    else dropped.push({ entry_type: e.entry_type, verdict: v ? v.verdict : 'NO_VERDICT', reason: v ? v.reason : 'verifier did not return a verdict for this entry' })
  })
  if (dropped.length) {
    log(`${lo.id}: dropped ${dropped.length}/${entries.entries.length} — ${dropped.map((d) => d.verdict).join(', ')}`)
  }

  // Map the author's label back onto the misconception id the assembler mints,
  // so entries and misconceptions line up without the model having to guess ids.
  const slug = (t) => t.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40)
  const loTail = lo.id.split(':').pop()

  return {
    lo: lo.id,
    misconceptions: (misc.misconceptions || []).map((m) => ({
      id: `misc:${loTail}:${slug(m.label)}`,
      label: m.label,
      description: m.description,
      signal: m.signal || null,
    })),
    entries: kept.map((e) => ({
      entry_type: e.entry_type,
      misconception: e.misconception_label ? `misc:${loTail}:${slug(e.misconception_label)}` : null,
      title: e.title || null,
      source_page: e.source_page ?? lo.page ?? null,
      content: e.content,
    })),
    audit: { dropped },
  }
}))

const totals = records.reduce((a, r) => ({
  misconceptions: a.misconceptions + r.misconceptions.length,
  entries: a.entries + r.entries.length,
  dropped: a.dropped + r.audit.dropped.length,
}), { misconceptions: 0, entries: 0, dropped: 0 })

log(`library: ${totals.misconceptions} misconceptions, ${totals.entries} entries kept, ${totals.dropped} dropped by the verifier`)
log('ALL entries will load reviewed=false — the human gate is suspended (ADR-0007)')

return { records, totals }
